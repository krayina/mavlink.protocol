#!/usr/bin/env python3
"""Generates FixedArray{N}<T> types: the C# shape of MAVLink T[N] fields.

C# has no const generics, so every array length needs its own type. All of them
are produced from one template, so they can only differ in N and in the parts of
the API that depend on N.

Usage:

    # the lengths used by array fields of the dialect XMLs in a folder
    python generate-fixed-arrays.py --from-xml path/to/dialects

    # explicit lengths
    python generate-fixed-arrays.py --sizes 4 16 251

    # every length a MAVLink payload can hold (1..255)
    python generate-fixed-arrays.py --all

Options:
    --out DIR          output folder (default: generated_arrays next to this script)
    --namespace NAME   namespace of the generated types (default: Mavlink)
    --prune            delete FixedArray*.cs in DIR whose length is not generated
    --check            write nothing; exit 1 if any file is missing, stale or would be pruned
    --no-char          with --from-xml, skip the lengths of char[N] fields

The output is self-contained: it depends on nothing but the BCL. Requirements of
the consuming project: C# 12 (collection expressions); on netstandard2.0 the
System.Memory package; on netstandard2.0/2.1 polyfills for
CollectionBuilderAttribute and (2.1 only) UnscopedRefAttribute, e.g. PolySharp.

Text (MAVLink char[N]) is stored as FixedArray{N}<byte>; it is read and written
with ToMavlinkString / FromMavlinkString / MavlinkStringEquals: UTF-8, terminated
by the first NUL, or occupying all N bytes when there is none.
"""

import argparse
import glob
import os
import re
import sys

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
DEFAULT_OUT = os.path.join(SCRIPT_DIR, "generated_arrays")
DEFAULT_NAMESPACE = "Mavlink"
FILE_PATTERN = re.compile(r"^FixedArray(\d+)\.cs$")
HELPER_FILE = "FixedArrayThrowHelper.cs"

# The LEN header byte bounds a payload at 255 bytes, so no array field is longer.
MAX_LENGTH = 255

# Up to this length a constructor taking every element is emitted (generated
# deserializers of small arrays call it). Longer arrays are built from a span.
MAX_ELEMENT_CONSTRUCTOR = 16

# Up to this length ToString lists the elements; above it, prints the shape.
MAX_TO_STRING_ELEMENTS = 16

# Field declarations per line, to keep long arrays readable.
FIELDS_PER_LINE = 16

SPAN_API = "NETSTANDARD2_1_OR_GREATER || NETCOREAPP3_0_OR_GREATER"

HEADER = """// <auto-generated>
//   Generated by generate-fixed-arrays.py. Do not edit: change the script and regenerate.
// </auto-generated>
#nullable enable"""


def element_constructor(n):
    if n > MAX_ELEMENT_CONSTRUCTOR:
        return ""
    params = ", ".join(f"T e{i}" for i in range(n))
    assigns = "\n".join(f"\t\t_e{i} = e{i};" for i in range(n))
    return f"""
	public FixedArray{n}({params})
	{{
{assigns}
	}}
"""


def fields(n):
    names = [f"_e{i}" for i in range(n)]
    lines = []
    for start in range(0, n, FIELDS_PER_LINE):
        chunk = ", ".join(names[start:start + FIELDS_PER_LINE])
        last = start + FIELDS_PER_LINE >= n
        lines.append(f"\t\t{chunk}{';' if last else ','}")
    return "\tprivate readonly T\n" + "\n".join(lines)


def to_string(n):
    if n <= MAX_TO_STRING_ELEMENTS:
        return """	public override string ToString()
	{
		var builder = new StringBuilder("[");
		ref T first = ref Unsafe.AsRef(in _e0);
		for (int i = 0; i < N; i++)
		{
			if (i != 0)
			{
				builder.Append(", ");
			}
			T value = Unsafe.Add(ref first, i);
			builder.Append(value is IFormattable formattable
				? formattable.ToString(null, CultureInfo.InvariantCulture)
				: value.ToString());
		}
		return builder.Append(']').ToString();
	}"""
    return """	public override string ToString()
		=> typeof(T).Name + "[" + N.ToString(CultureInfo.InvariantCulture) + "]";"""


def render_array(n, namespace):
    return f"""{HEADER}
using System.Buffers;
using System.Collections;
using System.Diagnostics;
using System.Diagnostics.CodeAnalysis;
using System.Globalization;
using System.Runtime.CompilerServices;
using System.Runtime.InteropServices;
using System.Text;

namespace {namespace};

/// <summary>
/// Fixed-length array of {n} elements stored inline: the C# shape of a MAVLink <c>T[{n}]</c> field.
/// </summary>
/// <remarks>
/// <para>
/// No heap allocation, value semantics (element-wise equality, so DTO record equality
/// works), and <c>default</c> is a valid all-zero array — exactly what a zero-filled
/// payload decodes to. The length is part of the type, so an array of the wrong length
/// cannot be assigned to a message field.
/// </para>
/// <para>
/// The public shape is identical on every target framework. <see cref="AsSpan"/> needs a
/// span over a managed reference and is absent on netstandard2.0; <see cref="CopyTo(Span{{T}})"/>,
/// the indexer and enumeration work everywhere.
/// </para>
/// <para>
/// Build it with a collection expression (<c>[a, b, ...]</c> or <c>[.. buffer]</c>, exactly
/// {n} elements) or, for a partially filled array, with <see cref="FromPrefix"/>.
/// MAVLink text (<c>char[{n}]</c>) is a <c>FixedArray{n}&lt;byte&gt;</c>; see
/// <see cref="FixedArray{n}.ToMavlinkString"/>.
/// </para>
/// </remarks>
[CollectionBuilder(typeof(FixedArray{n}), nameof(FixedArray{n}.Create))]
[DebuggerDisplay("{{ToString(),nq}}")]
public readonly struct FixedArray{n}<T> : IEquatable<FixedArray{n}<T>>, IReadOnlyList<T>
	where T : unmanaged
{{
	private const int N = {n};

	// Identical unmanaged fields under sequential layout are laid out contiguously with
	// stride sizeof(T) (no GC references, so the runtime cannot reorder them). Only _e0 is
	// named in code; every element is reached through Unsafe.Add from it.
#pragma warning disable CS0169, CS0649
{fields(n)}
#pragma warning restore CS0169, CS0649
{element_constructor(n)}
	/// <summary>
	/// Copies exactly {n} elements from <paramref name="values"/>.
	/// </summary>
	/// <exception cref="ArgumentException"><paramref name="values"/> is not {n} elements long.</exception>
	public FixedArray{n}(ReadOnlySpan<T> values)
	{{
		if (values.Length != N)
		{{
			throw FixedArrayThrowHelper.LengthMismatch(N, values.Length);
		}}

		this = default;
		Fill(ref Unsafe.AsRef(in _e0), values);
	}}

	/// <summary>
	/// Copies up to {n} elements from <paramref name="values"/>; the remaining elements are zero.
	/// For fields that carry their used length in another field (count, length, size...).
	/// </summary>
	/// <exception cref="ArgumentException"><paramref name="values"/> is longer than {n} elements.</exception>
	public static FixedArray{n}<T> FromPrefix(ReadOnlySpan<T> values)
	{{
		if (values.Length > N)
		{{
			throw FixedArrayThrowHelper.TooManyElements(N, values.Length);
		}}

		FixedArray{n}<T> result = default;
		Fill(ref Unsafe.AsRef(in result._e0), values);
		return result;
	}}

	public int Length => N;

	int IReadOnlyCollection<T>.Count => N;

	public T this[int index]
	{{
		get
		{{
			if ((uint)index >= N)
			{{
				throw FixedArrayThrowHelper.IndexOutOfRange(index, N);
			}}
			return Unsafe.Add(ref Unsafe.AsRef(in _e0), index);
		}}
	}}

	/// <summary>
	/// Returns a copy with the element at <paramref name="index"/> replaced.
	/// </summary>
	public FixedArray{n}<T> With(int index, T value)
	{{
		if ((uint)index >= N)
		{{
			throw FixedArrayThrowHelper.IndexOutOfRange(index, N);
		}}

		FixedArray{n}<T> copy = this;
		Unsafe.Add(ref Unsafe.AsRef(in copy._e0), index) = value;
		return copy;
	}}

#if {SPAN_API}
	/// <summary>
	/// The elements as a span pointing into this value, without copying; the compiler
	/// prevents it from outliving the value. Not available on netstandard2.0.
	/// </summary>
	[UnscopedRef]
	public ReadOnlySpan<T> AsSpan() => MemoryMarshal.CreateReadOnlySpan(ref Unsafe.AsRef(in _e0), N);
#endif

	/// <summary>
	/// Copies all {n} elements into <paramref name="destination"/>.
	/// </summary>
	public void CopyTo(Span<T> destination) => CopyTo(destination, N);

	/// <summary>
	/// Copies the first <paramref name="count"/> elements into <paramref name="destination"/>.
	/// </summary>
	public void CopyTo(Span<T> destination, int count)
	{{
		if ((uint)count > N)
		{{
			throw FixedArrayThrowHelper.CountOutOfRange(count, N);
		}}
		if (destination.Length < count)
		{{
			throw FixedArrayThrowHelper.DestinationTooShort(count, destination.Length);
		}}

		if (count != 0)
		{{
			Unsafe.CopyBlockUnaligned(
				ref Unsafe.As<T, byte>(ref MemoryMarshal.GetReference(destination)),
				ref Unsafe.As<T, byte>(ref Unsafe.AsRef(in _e0)),
				(uint)(count * Unsafe.SizeOf<T>()));
		}}
	}}

	public T[] ToArray()
	{{
		var result = new T[N];
		CopyTo(result);
		return result;
	}}

	public Enumerator GetEnumerator() => new(this);

	IEnumerator<T> IEnumerable<T>.GetEnumerator() => GetEnumerator();

	IEnumerator IEnumerable.GetEnumerator() => GetEnumerator();

	// Element-wise on purpose: a bytewise compare would read padding inside T
	// (e.g. Invalidatable<short>) and would treat NaN payloads as different values.
	public bool Equals(FixedArray{n}<T> other)
	{{
		var comparer = EqualityComparer<T>.Default;
		ref T left = ref Unsafe.AsRef(in _e0);
		ref T right = ref Unsafe.AsRef(in other._e0);
		for (int i = 0; i < N; i++)
		{{
			if (!comparer.Equals(Unsafe.Add(ref left, i), Unsafe.Add(ref right, i)))
			{{
				return false;
			}}
		}}
		return true;
	}}

	public override bool Equals(object? obj) => obj is FixedArray{n}<T> other && Equals(other);

	public override int GetHashCode()
	{{
		var comparer = EqualityComparer<T>.Default;
		ref T first = ref Unsafe.AsRef(in _e0);
		int hash = N;
		for (int i = 0; i < N; i++)
		{{
			hash = unchecked((hash * 31) + comparer.GetHashCode(Unsafe.Add(ref first, i)));
		}}
		return hash;
	}}

	public static bool operator ==(FixedArray{n}<T> left, FixedArray{n}<T> right) => left.Equals(right);

	public static bool operator !=(FixedArray{n}<T> left, FixedArray{n}<T> right) => !left.Equals(right);

{to_string(n)}

	private static void Fill(ref T first, ReadOnlySpan<T> values)
	{{
		if (!values.IsEmpty)
		{{
			Unsafe.CopyBlockUnaligned(
				ref Unsafe.As<T, byte>(ref first),
				ref Unsafe.As<T, byte>(ref MemoryMarshal.GetReference(values)),
				(uint)(values.Length * Unsafe.SizeOf<T>()));
		}}
	}}

	/// <summary>
	/// Allocation-free enumerator over a copy of the array.
	/// </summary>
	[SuppressMessage("Performance", "CA1815:Override equals and operator equals on value types",
		Justification = "Mutable iteration cursor; comparing enumerators is meaningless.")]
	public struct Enumerator : IEnumerator<T>
	{{
		private readonly FixedArray{n}<T> _array;
		private int _index;

		internal Enumerator(FixedArray{n}<T> array)
		{{
			_array = array;
			_index = -1;
		}}

		public readonly T Current => _array[_index];

		readonly object IEnumerator.Current => Current;

		public bool MoveNext() => ++_index < N;

		public void Reset() => _index = -1;

		public readonly void Dispose()
		{{
		}}
	}}
}}

/// <summary>
/// Factory for <see cref="FixedArray{n}{{T}}"/> (also the collection-expression builder)
/// and MAVLink text access for <c>FixedArray{n}&lt;byte&gt;</c>.
/// </summary>
/// <remarks>
/// MAVLink text (<c>char[{n}]</c>) is UTF-8. It ends at the first NUL byte, or occupies all
/// {n} bytes when there is none: a {n}-character value carries no terminator.
/// </remarks>
public static class FixedArray{n}
{{
	private const int N = {n};

	/// <inheritdoc cref="FixedArray{n}{{T}}(ReadOnlySpan{{T}})"/>
	public static FixedArray{n}<T> Create<T>(ReadOnlySpan<T> values) where T : unmanaged => new(values);

	/// <summary>
	/// Decodes MAVLink text: UTF-8 up to the first NUL, or all {n} bytes. Invalid UTF-8 is
	/// replaced with U+FFFD, never thrown on — the bytes come from the wire.
	/// </summary>
	public static string ToMavlinkString(this in FixedArray{n}<byte> text)
	{{
#if {SPAN_API}
		ReadOnlySpan<byte> bytes = text.AsSpan();
		return Encoding.UTF8.GetString(bytes.Slice(0, TextLength(bytes)));
#else
		byte[] buffer = ArrayPool<byte>.Shared.Rent(N);
		try
		{{
			text.CopyTo(buffer);
			return Encoding.UTF8.GetString(buffer, 0, TextLength(buffer.AsSpan(0, N)));
		}}
		finally
		{{
			ArrayPool<byte>.Shared.Return(buffer);
		}}
#endif
	}}

	/// <summary>
	/// Encodes <paramref name="value"/> as MAVLink text: UTF-8, NUL-padded to {n} bytes.
	/// A value of exactly {n} bytes is stored without a terminator, as the protocol requires.
	/// </summary>
	/// <exception cref="ArgumentNullException"><paramref name="value"/> is null.</exception>
	/// <exception cref="ArgumentException">
	/// <paramref name="value"/> contains NUL, or its UTF-8 form is longer than {n} bytes.
	/// It is never truncated: a shortened parameter id would silently name another parameter.
	/// </exception>
	public static FixedArray{n}<byte> FromMavlinkString(string value)
	{{
		if (value is null)
		{{
			throw new ArgumentNullException(nameof(value));
		}}
		if (value.IndexOf('\\0') >= 0)
		{{
			throw FixedArrayThrowHelper.TextContainsNul();
		}}

		int byteCount = Encoding.UTF8.GetByteCount(value);
		if (byteCount > N)
		{{
			throw FixedArrayThrowHelper.TextTooLong(byteCount, N);
		}}

#if {SPAN_API}
		Span<byte> bytes = stackalloc byte[N];
		int written = Encoding.UTF8.GetBytes(value, bytes);
		return FixedArray{n}<byte>.FromPrefix(bytes.Slice(0, written));
#else
		return FixedArray{n}<byte>.FromPrefix(Encoding.UTF8.GetBytes(value));
#endif
	}}

	/// <summary>
	/// True when the MAVLink text equals <paramref name="value"/> (ordinal, on the UTF-8 bytes).
	/// Allocation-free on netstandard2.1 and later. A value that cannot be stored (null,
	/// containing NUL, longer than {n} UTF-8 bytes) is never equal.
	/// </summary>
	public static bool MavlinkStringEquals(this in FixedArray{n}<byte> text, string? value)
	{{
		if (value is null || value.IndexOf('\\0') >= 0)
		{{
			return false;
		}}

#if {SPAN_API}
		ReadOnlySpan<byte> bytes = text.AsSpan();
		int length = TextLength(bytes);
		if (Encoding.UTF8.GetByteCount(value) != length)
		{{
			return false;
		}}
		Span<byte> encoded = stackalloc byte[N];
		Encoding.UTF8.GetBytes(value, encoded);
		return bytes.Slice(0, length).SequenceEqual(encoded.Slice(0, length));
#else
		byte[] encoded = Encoding.UTF8.GetBytes(value);
		if (encoded.Length > N)
		{{
			return false;
		}}
		for (int i = 0; i < encoded.Length; i++)
		{{
			if (text[i] != encoded[i])
			{{
				return false;
			}}
		}}
		// Equal only if the text ends exactly here.
		return encoded.Length == N || text[encoded.Length] == 0;
#endif
	}}

	// Length of the text: up to the first NUL, or all of it.
	private static int TextLength(ReadOnlySpan<byte> bytes)
	{{
		int nul = bytes.IndexOf((byte)0);
		return nul >= 0 ? nul : bytes.Length;
	}}
}}
"""


def render_helper(namespace):
    return f"""{HEADER}
using System.Runtime.CompilerServices;

namespace {namespace};

/// <summary>
/// Exception factories shared by the generated FixedArray types: <c>throw FixedArrayThrowHelper.X(...)</c>.
/// The <c>throw</c> stays at the call site; the formatting exists once instead of once per array length.
/// </summary>
internal static class FixedArrayThrowHelper
{{
	[MethodImpl(MethodImplOptions.NoInlining)]
	public static ArgumentException LengthMismatch(int required, int actual)
		=> new ArgumentException($"Exactly {{required}} elements are required; got {{actual}}.", "values");

	[MethodImpl(MethodImplOptions.NoInlining)]
	public static ArgumentException TooManyElements(int capacity, int actual)
		=> new ArgumentException($"At most {{capacity}} elements fit; got {{actual}}.", "values");

	[MethodImpl(MethodImplOptions.NoInlining)]
	public static ArgumentOutOfRangeException IndexOutOfRange(int index, int length)
		=> new ArgumentOutOfRangeException("index", index, $"Index must be in [0, {{length}}).");

	[MethodImpl(MethodImplOptions.NoInlining)]
	public static ArgumentOutOfRangeException CountOutOfRange(int count, int length)
		=> new ArgumentOutOfRangeException("count", count, $"Count must be in [0, {{length}}].");

	[MethodImpl(MethodImplOptions.NoInlining)]
	public static ArgumentException DestinationTooShort(int required, int actual)
		=> new ArgumentException($"Destination is {{actual}} elements; at least {{required}} are required.", "destination");

	[MethodImpl(MethodImplOptions.NoInlining)]
	public static ArgumentException TextTooLong(int byteCount, int capacity)
		=> new ArgumentException($"The text is {{byteCount}} UTF-8 bytes; at most {{capacity}} fit.", "value");

	[MethodImpl(MethodImplOptions.NoInlining)]
	public static ArgumentException TextContainsNul()
		=> new ArgumentException("MAVLink text cannot contain NUL: it would end the text on the wire.", "value");
}}
"""


def lengths_from_xml(folder, include_char):
    found = set()
    files = sorted(glob.glob(os.path.join(folder, "*.xml")))
    if not files:
        sys.exit(f"no *.xml in {folder}")
    for path in files:
        with open(path, encoding="utf-8") as f:
            for element_type, length in re.findall(r'<field[^>]*\btype="(\w+)\[(\d+)\]"', f.read()):
                if element_type == "char" and not include_char:
                    continue
                found.add(int(length))
    return found


def encode(text):
    # UTF-8 with BOM, LF line endings.
    return b"\xef\xbb\xbf" + text.encode("utf-8")


def sync(path, content, check, changed):
    # Line endings are not content: with core.autocrlf (Windows) git checks files out
    # with CRLF. Compare without CR, and keep the file's existing line endings when
    # rewriting it, so regenerating an unchanged file leaves it byte-identical.
    current = open(path, "rb").read() if os.path.exists(path) else None
    if current is not None and current.replace(b"\r\n", b"\n") == content:
        return
    changed.append(path)
    if not check:
        if current is not None and b"\r\n" in current:
            content = content.replace(b"\n", b"\r\n")
        with open(path, "wb") as f:
            f.write(content)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--sizes", type=int, nargs="+", metavar="N")
    mode.add_argument("--from-xml", metavar="DIR")
    mode.add_argument("--all", action="store_true")
    parser.add_argument("--out", default=DEFAULT_OUT)
    parser.add_argument("--namespace", default=DEFAULT_NAMESPACE)
    parser.add_argument("--prune", action="store_true")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--no-char", action="store_true")
    args = parser.parse_args()

    if not re.fullmatch(r"[A-Za-z_]\w*(\.[A-Za-z_]\w*)*", args.namespace):
        sys.exit(f"invalid namespace: {args.namespace}")

    if args.all:
        lengths = set(range(1, MAX_LENGTH + 1))
    elif args.from_xml:
        lengths = lengths_from_xml(args.from_xml, include_char=not args.no_char)
    else:
        lengths = set(args.sizes)

    bad = sorted(n for n in lengths if not 1 <= n <= MAX_LENGTH)
    if bad:
        sys.exit(f"lengths must be in 1..{MAX_LENGTH}: {bad}")

    os.makedirs(args.out, exist_ok=True)
    existing = {
        int(m.group(1)): os.path.join(args.out, name)
        for name in os.listdir(args.out)
        if (m := FILE_PATTERN.match(name))
    }

    changed, pruned = [], []
    sync(os.path.join(args.out, HELPER_FILE), encode(render_helper(args.namespace)), args.check, changed)
    for n in sorted(lengths):
        sync(os.path.join(args.out, f"FixedArray{n}.cs"), encode(render_array(n, args.namespace)), args.check, changed)

    if args.prune:
        for n, path in sorted(existing.items()):
            if n not in lengths:
                pruned.append(path)
                if not args.check:
                    os.remove(path)

    for path in changed:
        print(("stale   " if args.check else "write   ") + os.path.relpath(path))
    for path in pruned:
        print(("extra   " if args.check else "delete  ") + os.path.relpath(path))
    print(f"{len(lengths)} lengths: {', '.join(map(str, sorted(lengths)))}")

    if args.check and (changed or pruned):
        sys.exit(1)


if __name__ == "__main__":
    main()
